from __future__ import annotations

from pathlib import Path

from app.core.config import get_settings


_ALLOWED_AREAS = {"uploads", "exports", "previews", "tmp"}


def _absolute(path: Path) -> Path:
    """Resolve relative application paths against the current process cwd."""
    return path if path.is_absolute() else Path.cwd() / path


def confined_storage_path(value: str | Path | None, area: str) -> Path | None:
    """Resolve a persisted media path only when it stays inside ClipKaro storage.

    Database paths are normally generated by ClipKaro itself, but treating them
    as trusted filesystem capabilities would turn a corrupted/imported row into
    an arbitrary-file read/delete primitive. ``resolve(strict=False)`` also
    resolves existing symlink parents, so a symlink underneath storage cannot
    escape the configured area.
    """
    if area not in _ALLOWED_AREAS or value is None:
        return None
    raw = str(value).strip()
    if not raw:
        return None
    try:
        root = _absolute(get_settings().storage_root).resolve(strict=False)
        base = (root / area).resolve(strict=False)
        candidate = _absolute(Path(raw)).resolve(strict=False)
        candidate.relative_to(base)
        return candidate
    except (OSError, RuntimeError, ValueError):
        return None


def confined_upload_path(value: str | Path | None) -> Path | None:
    return confined_storage_path(value, "uploads")


def confined_export_path(value: str | Path | None) -> Path | None:
    return confined_storage_path(value, "exports")
